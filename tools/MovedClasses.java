import java.io.ByteArrayOutputStream;
import java.io.IOException;
import java.io.InputStream;
import java.io.UncheckedIOException;
import java.net.URI;
import java.net.http.HttpClient;
import java.net.http.HttpRequest;
import java.net.http.HttpResponse;
import java.nio.ByteBuffer;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.List;
import java.util.Map;
import java.util.TreeMap;
import java.util.concurrent.ExecutorService;
import java.util.concurrent.Executors;
import java.util.concurrent.Future;
import java.util.regex.Matcher;
import java.util.regex.Pattern;
import java.util.stream.Collectors;
import java.util.zip.ZipEntry;
import java.util.zip.ZipInputStream;

/**
 * Builds the table of Spring Boot classes that moved to another package between two versions.
 *
 * <p>It reads the list of Spring Boot artifacts from each version's BOM, downloads their jars from
 * Maven Central (cached in target/jars), and lists the public top-level classes of each. A class
 * "moved" when its old name is gone and exactly one class with the same simple name exists in the
 * new version.
 *
 * <pre>
 * java tools/MovedClasses.java 3.5.16 4.0.10 &gt; src/main/resources/io/github/jooaogui/bootleap/rule/moved-classes.tsv
 * </pre>
 */
public class MovedClasses {

    private static final String REPO = "https://repo1.maven.org/maven2/org/springframework/boot/";
    private static final Path CACHE = Path.of("target", "jars");
    private static final HttpClient HTTP = HttpClient.newBuilder().followRedirects(HttpClient.Redirect.NORMAL).build();

    private static final Pattern BOOT_ARTIFACT = Pattern.compile(
            "<groupId>org\\.springframework\\.boot</groupId>\\s*<artifactId>([\\w.-]+)</artifactId>");

    /** Build tooling, not code that applications import. Starters have no classes. */
    private static final Pattern SKIPPED = Pattern.compile(
            "spring-boot-starter.*|.*-plugin|spring-boot-loader.*|spring-boot-buildpack-platform|spring-boot-jarmode-.*"
                    + "|.*-processor|spring-boot-dependencies|spring-boot-parent");

    /**
     * Deprecated modules that keep old code working for a while. Pointing people there would be bad
     * advice, so their classes do not count as a new home (bootleap's jackson-3 rule covers them).
     */
    private static final Pattern COMPATIBILITY = Pattern.compile("spring-boot-jackson2");

    public static void main(String[] args) throws Exception {
        if (args.length != 2) {
            System.err.println("Usage: java tools/MovedClasses.java <old version> <new version>");
            System.exit(2);
        }
        String oldVersion = args[0];
        String newVersion = args[1];
        Map<String, String> oldClasses = publicClasses(oldVersion);
        Map<String, String> newClasses = publicClasses(newVersion);
        newClasses.values().removeIf(artifact -> COMPATIBILITY.matcher(artifact).matches());
        Map<String, List<String>> newBySimpleName = newClasses.keySet().stream()
                .collect(Collectors.groupingBy(MovedClasses::simpleName));

        System.out.println("# Spring Boot classes that moved to another package between " + oldVersion + " and " + newVersion + ".");
        System.out.println("# Generated by tools/MovedClasses.java from the jars on Maven Central. Do not edit by hand.");
        System.out.println("# old class\tnew class\tartifact that holds the new class");
        int moved = 0;
        int gone = 0;
        int ambiguous = 0;
        for (String oldClass : oldClasses.keySet()) {
            if (newClasses.containsKey(oldClass)) {
                continue;
            }
            List<String> candidates = newBySimpleName.getOrDefault(simpleName(oldClass), List.of());
            if (candidates.size() == 1) {
                String newClass = candidates.get(0);
                System.out.println(oldClass + "\t" + newClass + "\t" + newClasses.get(newClass));
                moved++;
            } else if (candidates.isEmpty()) {
                gone++;
            } else {
                ambiguous++;
            }
        }
        System.err.printf("%d classes in %s, %d in %s: %d moved, %d gone, %d ambiguous%n",
                oldClasses.size(), oldVersion, newClasses.size(), newVersion, moved, gone, ambiguous);
    }

    /** Public top-level classes of every Spring Boot artifact in a version, as class name to artifact. */
    private static Map<String, String> publicClasses(String version) throws Exception {
        String bom = new String(download("spring-boot-dependencies/" + version + "/spring-boot-dependencies-" + version + ".pom"));
        List<String> artifacts = new ArrayList<>();
        Matcher m = BOOT_ARTIFACT.matcher(bom);
        while (m.find()) {
            if (!SKIPPED.matcher(m.group(1)).matches() && !artifacts.contains(m.group(1))) {
                artifacts.add(m.group(1));
            }
        }
        ExecutorService pool = Executors.newFixedThreadPool(8);
        try {
            List<Future<Map<String, String>>> jobs = new ArrayList<>();
            for (String artifact : artifacts) {
                jobs.add(pool.submit(() -> publicClasses(artifact, version)));
            }
            Map<String, String> classes = new TreeMap<>();
            for (Future<Map<String, String>> job : jobs) {
                classes.putAll(job.get());
            }
            return classes;
        } finally {
            pool.shutdown();
        }
    }

    private static Map<String, String> publicClasses(String artifact, String version) throws IOException, InterruptedException {
        Map<String, String> classes = new TreeMap<>();
        byte[] jar = download(artifact + "/" + version + "/" + artifact + "-" + version + ".jar");
        if (jar == null) {
            return classes; // some BOM entries only publish a pom
        }
        try (ZipInputStream zip = new ZipInputStream(new java.io.ByteArrayInputStream(jar))) {
            for (ZipEntry e; (e = zip.getNextEntry()) != null; ) {
                String name = e.getName();
                if (!name.endsWith(".class") || name.contains("$") || name.startsWith("META-INF/")
                        || name.endsWith("package-info.class") || name.endsWith("module-info.class")) {
                    continue;
                }
                byte[] bytes = zip.readAllBytes();
                if (bytes.length < 10 || ByteBuffer.wrap(bytes).getInt() != 0xCAFEBABE) {
                    System.err.println("Not a class file, skipped: " + artifact + "!" + name);
                    continue;
                }
                if (isPublic(bytes)) {
                    classes.put(name.substring(0, name.length() - ".class".length()).replace('/', '.'), artifact);
                }
            }
        }
        return classes;
    }

    /** Reads the access flags of a class file, which come right after its constant pool. */
    static boolean isPublic(byte[] classFile) {
        ByteBuffer buf = ByteBuffer.wrap(classFile);
        buf.position(8);
        int count = buf.getShort() & 0xffff;
        for (int i = 1; i < count; i++) {
            int tag = buf.get() & 0xff;
            switch (tag) {
                case 1 -> { // Utf8: read the length first, it moves the buffer
                    int length = buf.getShort() & 0xffff;
                    buf.position(buf.position() + length);
                }
                case 7, 8, 16, 19, 20 -> buf.position(buf.position() + 2);
                case 15 -> buf.position(buf.position() + 3);
                case 3, 4, 9, 10, 11, 12, 17, 18 -> buf.position(buf.position() + 4);
                case 5, 6 -> { // Long and Double take two slots
                    buf.position(buf.position() + 8);
                    i++;
                }
                default -> throw new IllegalStateException("Unknown constant pool tag " + tag);
            }
        }
        int access = buf.getShort() & 0xffff;
        boolean isPublic = (access & 0x0001) != 0;
        boolean isSynthetic = (access & 0x1000) != 0;
        return isPublic && !isSynthetic;
    }

    /** Downloads a file from Maven Central, or returns null when it does not exist. */
    private static byte[] download(String path) throws IOException, InterruptedException {
        Path cached = CACHE.resolve(path);
        if (Files.exists(cached)) {
            return Files.readAllBytes(cached);
        }
        HttpResponse<InputStream> response = HTTP.send(
                HttpRequest.newBuilder(URI.create(REPO + path)).build(), HttpResponse.BodyHandlers.ofInputStream());
        try (InputStream in = response.body()) {
            if (response.statusCode() == 404) {
                return null;
            }
            if (response.statusCode() != 200) {
                throw new IOException("HTTP " + response.statusCode() + " for " + path);
            }
            ByteArrayOutputStream bytes = new ByteArrayOutputStream();
            in.transferTo(bytes);
            Files.createDirectories(cached.getParent());
            Files.write(cached, bytes.toByteArray());
            return bytes.toByteArray();
        }
    }

    private static String simpleName(String className) {
        return className.substring(className.lastIndexOf('.') + 1);
    }
}
