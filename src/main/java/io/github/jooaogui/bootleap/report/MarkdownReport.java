package io.github.jooaogui.bootleap.report;

import java.io.PrintStream;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;

import io.github.jooaogui.bootleap.rule.Finding;

/**
 * GitHub flavored Markdown, made for a pull request comment: findings grouped by rule,
 * a fix shared by the whole group printed once, and long groups folded.
 */
public final class MarkdownReport implements Report {

    /** Groups longer than this are folded inside a details block. */
    static final int FOLD_AFTER = 5;

    @Override
    public void print(String context, List<Finding> findings, PrintStream out) {
        if (findings.isEmpty()) {
            out.println("### bootleap: no known Spring Boot 4 problems found");
            out.println();
            out.println(escape(context));
        } else {
            out.println("### bootleap: " + findings.size() + (findings.size() == 1 ? " thing" : " things")
                    + " to fix before Spring Boot 4");
            out.println();
            out.println(escape(context));
            Map<String, List<Finding>> byRule = new LinkedHashMap<>();
            findings.forEach(f -> byRule.computeIfAbsent(f.ruleId(), k -> new ArrayList<>()).add(f));
            byRule.forEach((rule, group) -> printGroup(rule, group, out));
        }
        out.println();
        out.println("<sub>Generated by [bootleap](https://github.com/JooaoGui/bootleap).</sub>");
    }

    private static void printGroup(String rule, List<Finding> group, PrintStream out) {
        boolean sharedFix = group.stream().map(Finding::fix).distinct().count() == 1;
        boolean fold = group.size() > FOLD_AFTER;
        out.println();
        out.println("#### `" + rule + "` (" + group.size() + ")");
        out.println();
        if (sharedFix) {
            out.println("**Fix:** " + escape(group.get(0).fix()));
            out.println();
        }
        if (fold) {
            out.println("<details><summary>Show " + group.size() + " places</summary>");
            out.println();
        }
        for (Finding f : group) {
            out.println("- `" + f.location() + "`: " + escape(f.problem()));
            if (!sharedFix) {
                out.println("  **Fix:** " + escape(f.fix()));
            }
        }
        if (fold) {
            out.println();
            out.println("</details>");
        }
    }

    /** Keeps names like tools.jackson.* or spring_boot from turning into Markdown formatting. */
    static String escape(String text) {
        return text.replace("\\", "\\\\")
                .replace("`", "\\`")
                .replace("*", "\\*")
                .replace("_", "\\_")
                .replace("<", "&lt;")
                .replace(">", "&gt;");
    }
}
