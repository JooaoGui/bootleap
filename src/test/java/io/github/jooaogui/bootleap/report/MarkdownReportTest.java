package io.github.jooaogui.bootleap.report;

import static org.assertj.core.api.Assertions.assertThat;

import java.io.ByteArrayOutputStream;
import java.io.PrintStream;
import java.nio.charset.StandardCharsets;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.List;

import org.junit.jupiter.api.Test;

import io.github.jooaogui.bootleap.rule.Finding;

class MarkdownReportTest {

    private static final String CONTEXT = "Checking against Spring Boot 4.1 (found 4.1.2 in build.gradle:3).";

    @Test
    void saysWhenNothingWasFound() {
        assertThat(print(List.of())).startsWith(String.join("\n",
                "### bootleap: no known Spring Boot 4 problems found",
                "",
                CONTEXT,
                ""));
    }

    @Test
    void groupsFindingsByRule() {
        String report = print(List.of(
                new Finding("artifact", Path.of("build.gradle"), 6, "aop was renamed.", "Use aspectj."),
                new Finding("artifact", Path.of("build.gradle"), 7, "undertow was dropped.", "Use Tomcat."),
                new Finding("mock-bean", Path.of("A.java"), 4, "@MockBean was removed.", "Use @MockitoBean.")));

        assertThat(report).startsWith(String.join("\n",
                "### bootleap: 3 things to fix before Spring Boot 4",
                "",
                CONTEXT,
                "",
                "#### `artifact` (2)",
                "",
                "- `build.gradle:6`: aop was renamed.",
                "  **Fix:** Use aspectj.",
                "- `build.gradle:7`: undertow was dropped.",
                "  **Fix:** Use Tomcat.",
                "",
                "#### `mock-bean` (1)",
                "",
                "**Fix:** Use @MockitoBean.",
                "",
                "- `A.java:4`: @MockBean was removed.",
                ""));
        assertThat(report).endsWith("<sub>Generated by [bootleap](https://github.com/JooaoGui/bootleap).</sub>\n");
    }

    @Test
    void foldsLongGroups() {
        List<Finding> findings = new ArrayList<>();
        for (int i = 1; i <= 6; i++) {
            findings.add(new Finding("jackson-3", Path.of("F" + i + ".java"), 3, "Uses Jackson 2.", "Change the imports."));
        }

        assertThat(print(findings))
                .contains("**Fix:** Change the imports.\n\n<details><summary>Show 6 places</summary>")
                .containsOnlyOnce("Change the imports.")
                .contains("- `F6.java:3`: Uses Jackson 2.\n\n</details>");
    }

    @Test
    void escapesMarkdownCharacters() {
        assertThat(MarkdownReport.escape("Change the imports to tools.jackson.* and keep <T> in my_var"))
                .isEqualTo("Change the imports to tools.jackson.\\* and keep &lt;T&gt; in my\\_var");
    }

    private static String print(List<Finding> findings) {
        ByteArrayOutputStream bytes = new ByteArrayOutputStream();
        PrintStream out = new PrintStream(bytes, true, StandardCharsets.UTF_8);
        new MarkdownReport().print(CONTEXT, findings, out);
        return bytes.toString(StandardCharsets.UTF_8).replace("\r\n", "\n");
    }
}
